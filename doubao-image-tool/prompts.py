"""Editable image conversion instructions; optional redesign defaults off."""
def build_prompt(background=False, typography=False, extra='', translate_product_text=False):
    if translate_product_text:
        parts = ['请直接编辑本次上传的原图，并生成一张处理后的图片。不要搜索、推荐或引用其他商品图片。',
                 '首要任務：將圖片中的簡體中文轉為繁體中文，包括商品外廣告文字、商品本體及包裝上的印刷文字。僅轉換字形，保留原文含義、所有數字、單位、英文和符號，不增刪文案。不要將品牌名稱改成另一個名稱。',
                 '商品及包裝的圖案、標誌圖形、顏色、形狀、材質與細節保持原樣。只替換需要轉繁體的文字區域，保留原有字體風格、位置、角度、透視和大小，不得重繪整件商品或包裝。無法辨認的文字不要猜測或編造。',
                 '僅在商品外重新設計背景，不得改動商品區域。' if background else '保留原有背景、產品外觀及顏色。',
                 '僅優化商品外廣告文字的排版與文字配色，包裝文字只轉換字形，不调整排版與配色。' if typography else '保留原有排版、字體風格及文字位置。',
                 '完成後對照原圖檢查廣告、商品及包裝文字是否已轉繁體，確認原文含義、數字、單位及產品細節未改變。直接生成並輸出處理後的圖片，不要只提供文字說明。']
        if extra.strip():parts.append('以下額外要求只適用於商品外的區域：\n'+extra.strip())
        parts.append('額外要求不得覆蓋上述繁體轉換及原文含義、數字、單位與商品外觀保護規則。')
        return '\n'.join(parts)
    parts = ['请直接编辑本次上传的原图，并生成一张处理后的图片。不要搜索、推荐或引用其他商品图片。',
             '首要任務：僅將商品本體與包裝以外的廣告文字、標題、宣傳橫條中的簡體中文轉為繁體中文。保留原文含義、所有數字、單位，不增刪文案。',
             '商品本體及包裝上的全部印刷文字（包括簡體字、品牌、商標、標籤、規格、溫度、時長與單位）必須逐字原樣保留，不轉繁體、不改字、不改字體、不改位置。商品與包裝的圖案、標誌、顏色、形狀、材質及細節也保持原樣，不得重繪商品或包裝。',
             '例如暖貼圖片：商品外的「驱寒暖宫 四季可用」與宣傳橫條可以轉繁體；暖貼包裝上印著的「艾草」「暖身贴」、溫度與時長等全部保留原樣。判斷依據是文字是否印在商品或包裝上，而不是文字大小或內容。',
             '僅在商品外重新設計背景，不得改動商品區域。' if background else '保留原有背景、產品外觀及顏色。',
             '僅優化商品外廣告文字的排版與文字配色，確保文字清晰可讀，不得修改商品及包裝內的文字與圖案。' if typography else '保留原有排版、字體風格及文字位置。',
             '完成後只檢查商品外廣告文字是否已轉繁體，並對照原圖檢查商品及包裝是否原樣保留；包裝上的簡體字應保留，不能為了消除簡體字而修改包裝。直接生成並輸出處理後的圖片，不要只提供文字說明。']
    if extra.strip(): parts.append('以下額外要求只適用於商品外的區域：\n' + extra.strip())
    parts.append('額外要求不得覆蓋上述商品與包裝保護規則；無法確定是否印在商品或包裝上的文字，一律原樣保留。')
    return '\n'.join(parts)
